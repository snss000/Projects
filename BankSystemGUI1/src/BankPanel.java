    private void searchBankCode() {
        String inputID = JOptionPane.showInputDialog("Enter Bank Code to search:");

        if (inputID == null || inputID.trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please enter a Bank Code.");
            return;
        }

        try {
            String sql = "SELECT * FROM search_bankcode(?)"; //wala pa
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, inputID);

            ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                JTextArea textArea = new JTextArea(
                    "Bank Found!\n\n" +
                    "Bank Code: " + rs.getString("code") +
                    "\nBank Name: " + rs.getString("bname") +
                    "\nAddress: " + rs.getString("address") 
                );

                textArea.setLineWrap(true);
                textArea.setWrapStyleWord(true);
                textArea.setEditable(false);

                JScrollPane scrollPane = new JScrollPane(textArea);
                scrollPane.setPreferredSize(new Dimension(400, 250));

                JOptionPane.showMessageDialog(null, scrollPane, "Bank Details", JOptionPane.INFORMATION_MESSAGE);

            } else {
                JOptionPane.showMessageDialog(null, "Sorry! No record found.");
            }

            rs.close();
            pst.close();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Please enter a valid Bank Code.");
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Search failed: " + e.getMessage());
        }
    } 
        
