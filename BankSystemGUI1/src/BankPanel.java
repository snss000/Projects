    private void btnDelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDelActionPerformed
        // TODO add your handling code here:
        int confirm = JOptionPane.showConfirmDialog(null, "Delete this bank?", "Confirm", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            try {
                if (txtbankcode.getText() == null || txtbankcode.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(null, "Please enter a Branch Code.");
                return;
            }
                String sql = "DELETE FROM bank WHERE code=?";
                PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, txtbankcode.getText());

                int rowsDeleted = pst.executeUpdate();

                if (rowsDeleted > 0) {
                    JOptionPane.showMessageDialog(null, "Deleted successfully!");
                } else {
                    JOptionPane.showMessageDialog(null, "Bank code not found.");
                }
                
                txtbankcode.setText("");
                txtbankname.setText("");
                txtadd.setText("");

                pst.close();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "Delete failed!");
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_btnDelActionPerformed

