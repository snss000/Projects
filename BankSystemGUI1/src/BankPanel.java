    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        try {
            if (txtbankcode.getText() == null || txtbankcode.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(null, "Please enter a Branch Code.");
                return;
            }
            
            String sql = "UPDATE BANK SET bname=?, address=? WHERE code=?";
            PreparedStatement pst = conn.prepareStatement(sql);

            // kunin values mula sa text fields
            pst.setString(1, txtbankname.getText());
            pst.setString(2, txtadd.getText());
            pst.setString(3, txtbankcode.getText()); // code is VARCHAR(10)

            int rows = pst.executeUpdate();
            if (rows > 0) {
                JOptionPane.showMessageDialog(null, "Bank record updated successfully!");
            } else {
                JOptionPane.showMessageDialog(null, "No bank found with that Code.");
            }

            txtbankcode.setText("");
            txtbankname.setText("");
            txtadd.setText("");

            pst.close();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Update failed: " + e.getMessage());
            e.printStackTrace(System.err);
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

