    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        try {
                if (txtlono.getText().trim().isEmpty()) {
                    JOptionPane.showMessageDialog(null, "Loan Number is required to update a record.");
                    return;
                }

                String sql = "UPDATE loan SET amount=?, acct_type=?, acctno=? WHERE loanno=?";
                PreparedStatement pst = conn.prepareStatement(sql);

                pst.setDouble(1, Double.parseDouble(txtamount.getText()));

                String acctType = "";
                if (rbsavings.isSelected()) {
                    acctType = "Savings";
                } else if (rbtd.isSelected()) {
                    acctType = "Time Deposit";
                }
                pst.setString(2, acctType);
                pst.setString(3, txtaccno.getText());
                pst.setString(4, txtlono.getText());

                int rows = pst.executeUpdate();
                if (rows > 0) {
                    JOptionPane.showMessageDialog(null, "Loan record updated successfully!");
                } else {
                    JOptionPane.showMessageDialog(null, "No loan found with that Loan Number.");
                }

                txtlono.setText("");
                txtamount.setText("");
                buttonGroup1.clearSelection();            
                txtaccno.setText("");

                pst.close();

            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(null, "Invalid Amount. Please enter a number.");
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(null, "Update failed: " + e.getMessage());
                e.printStackTrace(System.err);
            }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDelActionPerformed
        // TODO add your handling code here:
        int confirm = JOptionPane.showConfirmDialog(null, "Delete this Loan?", "Confirm", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            try {
                String loanNo = txtlono.getText().trim();
                if (loanNo.isEmpty()) {
                    JOptionPane.showMessageDialog(null, "Please enter Loan Number.");
                    return;
                }

                String sql = "DELETE FROM loan WHERE TRIM(UPPER(loanno)) = ?";
                PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, loanNo.toUpperCase());

                int rowsDeleted = pst.executeUpdate();

                if (rowsDeleted > 0) {
                    JOptionPane.showMessageDialog(null, "Deleted successfully!");
                } else {
                    JOptionPane.showMessageDialog(null, "Loan number not found.");
                }

                txtlono.setText("");
                txtamount.setText("");
                buttonGroup1.clearSelection();            
                txtaccno.setText("");

                pst.close();
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(null, "Delete failed: " + e.getMessage());
                e.printStackTrace(System.err);
            }
        }
    }//GEN-LAST:event_btnDelActionPerformed

