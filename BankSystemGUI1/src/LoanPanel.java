    private void searchAccountNo() {
        String inputID = JOptionPane.showInputDialog("Enter Account No. to search:");

        if (inputID == null || inputID.trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please enter Account Number.");
            return;
        }

        try {
            String sql = "SELECT * FROM loan WHERE acctno = ?";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, inputID); // acctno is VARCHAR

            ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                JTextArea textArea = new JTextArea(
                    "Loan Information Found!\n\n" +
                    "Loan Number: " + rs.getString("loanno") +
                    "\nAmount: " + rs.getDouble("amount") +
                    "\nAccount Type: " + rs.getString("acct_type") +
                    "\nAccount Number: " + rs.getString("acctno")
                );

                textArea.setLineWrap(true);
                textArea.setWrapStyleWord(true);
                textArea.setEditable(false);

                JScrollPane scrollPane = new JScrollPane(textArea);
                scrollPane.setPreferredSize(new Dimension(400, 250));

                JOptionPane.showMessageDialog(null, scrollPane, "Loan Details", JOptionPane.INFORMATION_MESSAGE);

            } else {
                JOptionPane.showMessageDialog(null, "Sorry! No record found.");
            }

            rs.close();
            pst.close();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Search failed: " + e.getMessage());
            e.printStackTrace(System.err);
        }
    }
    
