    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        try {
            // Validation
            if (txtlono.getText().trim().isEmpty() || 
                txtamount.getText().trim().isEmpty() || 
                txtaccno.getText().trim().isEmpty() || 
                (!rbsavings.isSelected() && !rbtd.isSelected())) {

                JOptionPane.showMessageDialog(null, "Oops! All fields should have input!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            String sql = "INSERT INTO loan(loanno, amount, acct_type, acctno) VALUES (?, ?, ?, ?)";
            PreparedStatement pst = conn.prepareStatement(sql);

            pst.setString(1, txtlono.getText());
            pst.setDouble(2, Double.parseDouble(txtamount.getText()));

            String acctType = "";
            if (rbsavings.isSelected()) {
                acctType = "Savings";
            } else if (rbtd.isSelected()) {
                acctType = "Time Deposit";
            }
            pst.setString(3, acctType);
            pst.setString(4, txtaccno.getText());
            pst.executeUpdate();

            JOptionPane.showMessageDialog(null, "Loan saved successfully!");
            JOptionPane.showMessageDialog(null, "Thank you! <3");

            txtlono.setText("");
            txtamount.setText("");
            buttonGroup1.clearSelection();            
            txtaccno.setText("");

            pst.close();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Invalid Amount. Please enter a number.");
        } catch (SQLException e) { 
            JOptionPane.showMessageDialog(null, "Save failed: " + e.getMessage()); 
            e.printStackTrace(System.err); 
        }         
    }//GEN-LAST:event_btnSaveActionPerformed

